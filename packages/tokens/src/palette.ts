import { readableOn, type ColorTheme } from './styles.js'

/** CSS variables that paint one palette. */
export function paletteVariables(theme: ColorTheme): Record<string, string> {
  const vars: Record<string, string> = {
    '--background': theme.background,
    '--surface': theme.surface,
    '--foreground': theme.foreground,
    '--brand': theme.accent,
    '--brand-foreground': readableOn(theme.accent),
  }
  if (theme.mutedMix) {
    vars['--muted-foreground'] =
      `color-mix(in srgb, var(--foreground) ${theme.mutedMix}%, var(--background))`
  }
  return vars
}

interface StyleTarget {
  style: { setProperty(name: string, value: string): void }
  classList: { toggle(name: string, force?: boolean): unknown }
  setAttribute(name: string, value: string): void
}

/** Applies a palette to an element (usually document.documentElement). */
export function applyPalette(theme: ColorTheme, target: StyleTarget): void {
  target.setAttribute('data-style', theme.style)
  target.classList.toggle('dark', theme.mode === 'dark')
  for (const [name, value] of Object.entries(paletteVariables(theme))) {
    target.style.setProperty(name, value)
  }
}

/** CSS for every style's default palette, light under the style and dark under `.dark`. */
export function palettesCss(themes: readonly ColorTheme[], defaults: Record<string, string>): string {
  const blocks: string[] = [
    '/* Generated by scripts/build-css.mjs from src/styles.ts. Do not edit. */',
    '@layer base {',
  ]
  for (const [style, family] of Object.entries(defaults)) {
    for (const mode of ['light', 'dark'] as const) {
      const theme = themes.find((t) => t.style === style && t.id === `${family}-${mode}`)
      if (!theme) continue
      const selector =
        mode === 'light' ? `html[data-style='${style}']` : `html[data-style='${style}'].dark`
      const body = Object.entries(paletteVariables(theme))
        .map(([name, value]) => `    ${name}: ${value};`)
        .join('\n')
      blocks.push(`  ${selector} {\n${body}\n  }`)
    }
  }
  blocks.push('}', '')
  return blocks.join('\n')
}
