// Copies every style's theme.css from the style gallery repo into themes/.
// Usage: node scripts/sync-themes.mjs [path to the style repo]   (default ../../../style)
// It reads the repo's origin/main, so local edits in that checkout never leak in.
import { execFileSync } from 'node:child_process'
import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

const repo = resolve(process.argv[2] ?? '../../../style')
const git = (...a) => execFileSync('git', ['-C', repo, ...a], { encoding: 'utf8' })
git('fetch', '-q', 'origin')
const ids = git('ls-tree', '--name-only', 'origin/main', 'styles/').split('\n').filter(Boolean).map(p => p.split('/').pop())
rmSync('themes', { recursive: true, force: true })
mkdirSync('themes')
const synced = []
for (const id of ids) {
  try {
    writeFileSync(join('themes', `${id}.css`), git('show', `origin/main:styles/${id}/theme.css`))
    synced.push(id)
  } catch {
    console.warn(`skip ${id}: no theme.css on origin/main`)
  }
}
writeFileSync('src/themes.ts', `// Generated by scripts/sync-themes.mjs from the style gallery. Do not edit.
/** Gallery styles shipped as themes: import '@tetsustudio/tokens/themes/<id>.css'. */
export const GALLERY_THEMES = ${JSON.stringify(synced)} as const
export type GalleryThemeId = (typeof GALLERY_THEMES)[number]
`)
console.log(`synced ${synced.length} themes: ${synced.join(', ')}`)
console.log(readdirSync('themes').length === synced.length ? 'ok' : 'mismatch')
